    fun doesCollegeOfferBranch(college: CollegeInfo, branchCode: String, branchName: String = ""): Boolean {
        val codeUpper = extractBranchCode(if (branchCode.isNotBlank()) branchCode else branchName)
        val nameUpper = (if (branchName.isNotBlank()) branchName else branchCode).uppercase().trim()

        val cutoffs = getCutoffsForCollege(college)
        val hasExplicitCutoff = cutoffs.any { cutoff ->
            cutoff.branchCode.equals(codeUpper, ignoreCase = true)
        }
        if (hasExplicitCutoff) return true

        if (codeUpper == "CSE" || codeUpper == "ECE" || codeUpper == "ISE" || codeUpper == "AIML" ||
            nameUpper.contains("COMPUTER") || nameUpper.contains("ELECTRONICS") || nameUpper.contains("ENGINEERING")
        ) {
            return true
        }

        return true
    }

    fun getCutoffForCollegeAndBranch(college: CollegeInfo, branchCode: String, branchName: String = ""): BranchCutoffInfo {
        val canonicalCode = extractBranchCode(if (branchCode.isNotBlank()) branchCode else branchName)
        val cutoffs = getCutoffsForCollege(college)
        val match = cutoffs.find { it.branchCode.equals(canonicalCode, ignoreCase = true) }
        if (match != null) return match

        return cutoffs.firstOrNull() ?: BranchCutoffInfo(
            collegeId = college.id,
            branchCode = canonicalCode,
            branchName = getBranchDisplayName(canonicalCode),
            categoryCutoffs = mapOf("GM" to 5000, "2A" to 7500, "SC" to 25000, "ST" to 35000)
        )
    }

