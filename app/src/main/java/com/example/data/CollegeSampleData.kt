    fun extractBranchCode(input: String): String {
        val s = input.trim().uppercase()
        return when {
            s.contains("CSE") || s.contains("COMPUTER") -> "CSE"
            s.contains("AIML") || s.contains("ARTIFICIAL") || s.contains("MACHINE LEARNING") -> "AIML"
            s.contains("DATA SCIENCE") || s.contains("BIG ANALYTICS") -> "DS"
            s.contains("ISE") || s.contains("INFORMATION") -> "ISE"
            s.contains("ECE") || s.contains("ELECTRONICS & COMM") || s.contains("ELECTRONICS AND COMM") -> "ECE"
            s.contains("EEE") || s.contains("ELECTRICAL") -> "EEE"
            s.contains("ME") || s.contains("MECHANICAL") -> "ME"
            s.contains("CE") || s.contains("CIVIL") -> "CE"
            s.contains("AE") || s.contains("AEROSPACE") || s.contains("AERONAUTICAL") -> "AE"
            s.contains("BT") || s.contains("BIOTECH") || s.contains("BIOCHEMICAL") -> "BT"
            else -> "CSE"
        }
    }

